#!/usr/bin/env node
/**
 * Pin every llama.cpp release build that midnight.server can run, from one
 * GitHub release tag. Reads the asset names and the SHA-256 digests GitHub
 * publishes for them, and writes
 * packages/coding-agent/src/midnight/engine-builds.generated.ts.
 *
 * Usage: node scripts/generate-engine-pins.mjs <tag>   (e.g. b11166)
 *
 * Fails if any expected build is missing from the release, so an upgrade never
 * silently drops a platform or backend.
 */
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = "ggml-org/llama.cpp";
const OUT = join(
	dirname(fileURLToPath(import.meta.url)),
	"..",
	"packages",
	"coding-agent",
	"src",
	"midnight",
	"engine-builds.generated.ts",
);

const V = "[0-9.]+";
/**
 * platform -> backend -> asset name patterns. Every pattern must match exactly
 * one asset; the matching archives are extracted into one directory, in order.
 * `{tag}` is the release tag.
 */
const BUILDS = {
	"win32-x64": {
		cpu: ["llama-{tag}-bin-win-cpu-x64\\.zip"],
		vulkan: ["llama-{tag}-bin-win-vulkan-x64\\.zip"],
		"cuda-12": [`llama-{tag}-bin-win-cuda-12\\.${V}-x64\\.zip`, `cudart-llama-bin-win-cuda-12\\.${V}-x64\\.zip`],
		"cuda-13": [`llama-{tag}-bin-win-cuda-13\\.${V}-x64\\.zip`, `cudart-llama-bin-win-cuda-13\\.${V}-x64\\.zip`],
		rocm: [`llama-{tag}-bin-win-rocm-${V}-x64\\.zip`],
		sycl: ["llama-{tag}-bin-win-sycl-x64\\.zip"],
		openvino: [`llama-{tag}-bin-win-openvino-${V}-x64\\.zip`],
	},
	"win32-arm64": {
		cpu: ["llama-{tag}-bin-win-cpu-arm64\\.zip"],
		"cuda-13": [`llama-{tag}-bin-win-cuda-13\\.${V}-arm64\\.zip`, `cudart-llama-bin-win-cuda-13\\.${V}-arm64\\.zip`],
		opencl: ["llama-{tag}-bin-win-opencl-adreno-arm64\\.zip"],
	},
	"linux-x64": {
		cpu: ["llama-{tag}-bin-ubuntu-x64\\.tar\\.gz"],
		vulkan: ["llama-{tag}-bin-ubuntu-vulkan-x64\\.tar\\.gz"],
		"cuda-12": [
			`llama-{tag}-bin-ubuntu-cuda-12\\.${V}-x64\\.tar\\.gz`,
			`cudart-llama-{tag}-bin-ubuntu-cuda-12\\.${V}-x64\\.tar\\.gz`,
		],
		"cuda-13": [
			`llama-{tag}-bin-ubuntu-cuda-13\\.${V}-x64\\.tar\\.gz`,
			`cudart-llama-{tag}-bin-ubuntu-cuda-13\\.${V}-x64\\.tar\\.gz`,
		],
		rocm: [`llama-{tag}-bin-ubuntu-rocm-${V}-x64\\.tar\\.gz`],
		sycl: ["llama-{tag}-bin-ubuntu-sycl-fp32-x64\\.tar\\.gz"],
		openvino: [`llama-{tag}-bin-ubuntu-openvino-${V}-x64\\.tar\\.gz`],
	},
	"linux-arm64": {
		cpu: ["llama-{tag}-bin-ubuntu-arm64\\.tar\\.gz"],
		vulkan: ["llama-{tag}-bin-ubuntu-vulkan-arm64\\.tar\\.gz"],
		"cuda-13": [
			`llama-{tag}-bin-ubuntu-cuda-13\\.${V}-arm64\\.tar\\.gz`,
			`cudart-llama-{tag}-bin-ubuntu-cuda-13\\.${V}-arm64\\.tar\\.gz`,
		],
		hexagon: ["llama-{tag}-bin-linux-arm64-snapdragon\\.tar\\.gz"],
	},
	"darwin-x64": {
		cpu: ["llama-{tag}-bin-macos-x64\\.tar\\.gz"],
	},
	"darwin-arm64": {
		metal: ["llama-{tag}-bin-macos-arm64\\.tar\\.gz"],
	},
};

async function github(path) {
	const headers = { Accept: "application/vnd.github+json", "User-Agent": "midnight.server-generate-engine-pins" };
	if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
	const response = await fetch(`https://api.github.com/repos/${REPO}/${path}`, { headers });
	if (!response.ok) throw new Error(`GitHub API ${path}: HTTP ${response.status}`);
	return response.json();
}

const tag = process.argv[2];
if (!tag || !/^b\d+$/.test(tag)) {
	console.error("Usage: node scripts/generate-engine-pins.mjs <tag>   (e.g. b11166)");
	process.exit(2);
}

const release = await github(`releases/tags/${tag}`);
const commit = (await github(`commits/${tag}`)).sha;
const builds = {};
const problems = [];
for (const [platform, backends] of Object.entries(BUILDS)) {
	builds[platform] = {};
	for (const [backend, patterns] of Object.entries(backends)) {
		const archives = [];
		for (const pattern of patterns) {
			const regex = new RegExp(`^${pattern.replaceAll("{tag}", tag)}$`);
			const matches = release.assets.filter((asset) => regex.test(asset.name));
			if (matches.length !== 1) {
				problems.push(`${platform}/${backend}: ${matches.length} assets match ${regex}`);
				continue;
			}
			const [asset] = matches;
			const digest = /^sha256:([0-9a-f]{64})$/.exec(asset.digest ?? "");
			if (!digest) {
				problems.push(`${asset.name}: no SHA-256 digest published`);
				continue;
			}
			archives.push({ url: asset.browser_download_url, sizeBytes: asset.size, sha256: digest[1] });
		}
		builds[platform][backend] = archives;
	}
}
if (problems.length > 0) {
	console.error(problems.join("\n"));
	process.exit(1);
}

const source = `// Generated by scripts/generate-engine-pins.mjs from llama.cpp ${tag}. Do not edit.
import type { EngineBuilds, EngineRelease } from "./pins.ts";

export const ENGINE_RELEASE: EngineRelease = ${JSON.stringify({ name: "llama.cpp", release: tag, commit }, null, "\t")};

export const ENGINE_BUILDS: EngineBuilds = ${JSON.stringify(builds, null, "\t")};
`;
writeFileSync(OUT, source);
// Format like the rest of the tree so `npm run check` leaves the file unchanged.
const biome = join(dirname(fileURLToPath(import.meta.url)), "..", "node_modules", "@biomejs", "biome", "bin", "biome");
const formatted = spawnSync(process.execPath, [biome, "format", "--write", OUT], { stdio: "inherit" });
if (formatted.status !== 0) process.exit(formatted.status ?? 1);
console.log(`Wrote ${OUT}`);
