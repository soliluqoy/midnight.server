const assert = require("node:assert");
const { normalizeRelative } = require("./paths.js");
assert.strictEqual(normalizeRelative("a/./b/../c"), "a/c");
assert.strictEqual(normalizeRelative("a\\b\\..\\c"), "a/c");
assert.strictEqual(normalizeRelative("src\\lib/util.js"), "src/lib/util.js");
assert.strictEqual(normalizeRelative(".\\a\\\\b\\"), "a/b");
const rejects = (input) => { try { normalizeRelative(input); return false; } catch { return true; } };
assert.ok(rejects("..\\secret"), "escaping above the root is an error");
assert.ok(rejects("a/../../b"), "escaping above the root is an error");
console.log("pass");
