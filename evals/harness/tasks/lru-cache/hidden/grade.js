const assert = require("node:assert");
const { LRUCache } = require("./lru.js");
let c = new LRUCache(2);
c.set("a", 1); c.set("b", 2); c.get("a"); c.set("c", 3);
assert.strictEqual(c.get("a"), 1, "a was used recently and must survive");
assert.strictEqual(c.get("b"), undefined, "b is least recently used");
c = new LRUCache(2);
c.set("a", 1); c.set("b", 2); c.set("a", 10); c.set("c", 3);
assert.strictEqual(c.get("a"), 10, "updating a key refreshes it and must not evict it");
assert.strictEqual(c.get("b"), undefined);
assert.strictEqual(c.size, 2);
c = new LRUCache(1);
c.set("x", 1); c.set("x", 2);
assert.strictEqual(c.get("x"), 2);
assert.strictEqual(c.size, 1);
c = new LRUCache(3);
for (let i = 0; i < 100; i++) c.set(i % 5, i);
assert.strictEqual(c.size, 3);
