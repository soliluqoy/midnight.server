const assert = require("node:assert");
const { EventEmitter } = require("./emitter.js");
let e = new EventEmitter();
let count = 0;
e.once("x", () => count++);
e.emit("x"); e.emit("x");
assert.strictEqual(count, 1, "once fires once");
e = new EventEmitter();
const calls = [];
const a = () => { calls.push("a"); e.off("y", a); };
e.on("y", a); e.on("y", () => calls.push("b")); e.on("y", () => calls.push("c"));
e.emit("y");
assert.deepStrictEqual(calls, ["a", "b", "c"], "removing a listener during emit does not skip others");
e = new EventEmitter();
const seen = [];
e.once("z", (v) => seen.push(`1:${v}`)); e.once("z", (v) => seen.push(`2:${v}`));
e.emit("z", "p"); e.emit("z", "q");
assert.deepStrictEqual(seen, ["1:p", "2:p"]);
e = new EventEmitter();
let hits = 0;
const handler = () => hits++;
e.once("w", handler); e.off("w", handler); e.emit("w");
assert.strictEqual(hits, 0, "off removes a once listener by its original function");
assert.strictEqual(new EventEmitter().emit("none"), false);
console.log("pass");
